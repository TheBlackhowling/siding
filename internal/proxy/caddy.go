func GenerateCaddyfile(routes []Route, listen int) string {
	if listen <= 0 {
		listen = state.ProxyHTTPListen
	}
	var b strings.Builder
	b.WriteString("# Generated by siding. Do not edit.\n")
	b.WriteString("{\n")
	fmt.Fprintf(&b, "  http_port %d\n", listen)
	fmt.Fprintf(&b, "  admin 0.0.0.0:%d\n", state.ProxyAdminListen)
	b.WriteString("  auto_https off\n")
	b.WriteString("}\n\n")

	// One socket, Host matchers. A bare :80 site plus http://*.localhost
	// sites on the same port lets the catch-all steal stack Hosts and
	// 302 them to the board.
	fmt.Fprintf(&b, ":%d {\n", listen)
	b.WriteString("  @board host " + BoardHost + "\n")
	b.WriteString("  handle @board {\n")
	b.WriteString("    root * /srv/board\n")
	b.WriteString("    try_files {path} /index.html\n")
	b.WriteString("    file_server\n")
	b.WriteString("    header Cache-Control \"no-store\"\n")
	b.WriteString("  }\n")

	// Genie (and similar) redirect hostname == ROOT_DOMAIN to app.{hostname}.
	// If ROOT_DOMAIN was wrongly set to app.acme…, that becomes app.app.acme…
	// and the web wildcard would proxy it. Strip the doubled role first.
	// header_regexp Host — stock Caddy has no host_regexp matcher (2.11).
	b.WriteString("\n  @doubled header_regexp doubled Host ^app\\.(app\\..+)$\n")
	b.WriteString("  handle @doubled {\n")
	b.WriteString("    redir http://{http.regexp.doubled.1}{uri} 308\n")
	b.WriteString("  }\n")

	sites := groupCaddySites(routes)
	idx := 0
	for _, site := range sites {
		hosts := validCaddyHosts(site.hosts)
		if len(hosts) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n  @s%d host %s\n", idx, strings.Join(hosts, " "))
		fmt.Fprintf(&b, "  handle @s%d {\n", idx)
		fmt.Fprintf(&b, "    reverse_proxy %s:%d\n", UpstreamHost, site.upstream)
		b.WriteString("  }\n")
		idx++
	}

	board := SiteAddress(BoardHost, listen)
	b.WriteString("\n  handle {\n")
	b.WriteString("    header Content-Type \"text/html; charset=utf-8\"\n")
	fmt.Fprintf(&b, "    respond `%s` 404\n", unknownHostHTML(board))
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return b.String()
}

type caddySite struct {
	hosts    []string
	upstream int
}

func validCaddyHosts(hosts []string) []string {
	var out []string
	for _, h := range hosts {
		h = strings.TrimSpace(strings.ToLower(h))
		if h == "" {
			continue
		}
		if _, err := contract.CanonicalHostString(h); err != nil {
			continue
		}
		out = append(out, h)
	}
	return out
}

func groupCaddySites(routes []Route) []caddySite {
	var apis, webs []Route
	for _, r := range routes {
		if r.PortKey == "api" {
			apis = append(apis, r)
		} else {
			webs = append(webs, r)
		}
	}
	var out []caddySite
	for _, r := range apis {
		out = append(out, caddySite{hosts: []string{r.Host}, upstream: r.Upstream})
	}
	byUp := map[int][]string{}
	var order []int
	for _, r := range webs {
		if _, ok := byUp[r.Upstream]; !ok {
			order = append(order, r.Upstream)
		}
		byUp[r.Upstream] = appendHostMatcher(byUp[r.Upstream], r.Host)
		root := contract.RootHost(r.Host)
		byUp[r.Upstream] = appendHostMatcher(byUp[r.Upstream], root)
		byUp[r.Upstream] = appendHostMatcher(byUp[r.Upstream], "*."+root)
	}
	for _, up := range order {
		out = append(out, caddySite{hosts: byUp[up], upstream: up})
	}
	return out
}

func appendHostMatcher(hosts []string, host string) []string {
	host = strings.TrimSpace(strings.ToLower(host))
	if host == "" {
		return hosts
	}
	for _, have := range hosts {
		if have == host {
			return hosts
		}
	}
	return append(hosts, host)
}

func unknownHostHTML(board string) string {
	return `<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>No siding stack</title></head><body style="font:16px/1.5 system-ui,sans-serif;padding:2rem"><p>No siding stack for this Host.</p><p><a href="` + board + `">Open the siding board</a></p></body></html>`
}

func GenerateCompose(listen int) string {
	return GenerateComposeSkip(listen, nil)
}

func GenerateComposeSkip(listen int, skipPublish map[int]struct{}) string {
	if listen <= 0 {
		listen = state.ProxyHTTPListen
	}
	listens := HTTPListenPorts(listen)
	var ports strings.Builder
	seen := map[int]struct{}{}
	addPort := func(hostPort, containerPort int) {
		if skipPublish != nil {
			if _, skip := skipPublish[hostPort]; skip {
				return
			}
		}
		if _, ok := seen[hostPort]; ok {
			return
		}
		seen[hostPort] = struct{}{}
		fmt.Fprintf(&ports, "      - \"127.0.0.1:%d:%d\"\n", hostPort, containerPort)
	}
	for _, p := range listens {
		addPort(p, p)
	}
	addPort(state.ProxyAdminListen, state.ProxyAdminListen)

	return fmt.Sprintf(`# Generated by siding. Do not edit.
name: siding-proxy

services:
  caddy:
    image: %s
    pull_policy: %s
    container_name: %s
    ports:
%s    extra_hosts:
      - "host.docker.internal:host-gateway"
    volumes:
      - "./Caddyfile:/etc/caddy/Caddyfile:ro"
      - "./board/status.json:/srv/board/status.json:ro"
    restart: unless-stopped
`, composeImage(), composePullPolicy(), ContainerName, ports.String())
}

// SIDING_PROXY_IMAGE overrides the published tag so a local smoke image can
// run without pulling :latest (used while iterating on the board UI).
func composeImage() string {
	if img := strings.TrimSpace(os.Getenv("SIDING_PROXY_IMAGE")); img != "" {
		return img
	}
	return ProxyImage
}

func composePullPolicy() string {
	if strings.TrimSpace(os.Getenv("SIDING_PROXY_IMAGE")) != "" {
		return "never"
	}
	return "always"
}
